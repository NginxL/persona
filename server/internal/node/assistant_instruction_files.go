package node

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode/utf8"
)

// Antigravity truncates each rule file at 24,000 bytes after expanding includes. Keep generated entry and rule files
// below 20,000 bytes with headroom, rather than relying on that truncation boundary. Splitting here, instead of in the
// manager's prompt, keeps one complete source of instructions for every launcher and for older nodes.
const assistantInstructionChunkBytes = 19 * 1024

const (
	assistantInstructionRulePrefix = "persona-assistant-"
	assistantInstructionRuleMarker = "<!-- Generated by Persona from the complete assistant instructions. -->\n"
	antigravityInstructionHeader   = "---\ntrigger: always_on\n---\n"
)

// splitAssistantInstructions returns lossless UTF-8 chunks. Newlines stay with the preceding chunk; a long line is cut
// only at a rune boundary. The first chunk is the AGENTS.md / CLAUDE.md entry and subsequent chunks become native rules.
func splitAssistantInstructions(md string) []string {
	if len(md) <= assistantInstructionChunkBytes {
		return []string{md}
	}
	var chunks []string
	for len(md) > assistantInstructionChunkBytes {
		cut := assistantInstructionChunkBytes
		// Prefer a paragraph or line boundary, but do not let a long early line leave a tiny entry and oversized tail.
		if i := strings.LastIndex(md[:cut], "\n"); i >= assistantInstructionChunkBytes/2 {
			cut = i + 1
		}
		for cut > 0 && cut < len(md) && !utf8.RuneStart(md[cut]) {
			cut--
		}
		if cut == 0 {
			cut = assistantInstructionChunkBytes
			for cut < len(md) && !utf8.RuneStart(md[cut]) {
				cut++
			}
		}
		chunks = append(chunks, md[:cut])
		md = md[cut:]
	}
	return append(chunks, md)
}

func assistantInstructionRuleName(part int) string {
	return fmt.Sprintf("%s%06d.md", assistantInstructionRulePrefix, part)
}

// nativeInstructionPart removes only the generated envelope. The remaining bytes are exactly one chunk of the
// manager's original instructions. Antigravity requires always_on frontmatter for automatic, every-turn loading;
// Claude Code loads unconditional .claude/rules Markdown without frontmatter.
func nativeInstructionPart(b []byte, antigravity bool) (string, bool) {
	prefix := assistantInstructionRuleMarker
	if antigravity {
		prefix = antigravityInstructionHeader + prefix
	}
	if !strings.HasPrefix(string(b), prefix) {
		return "", false
	}
	return strings.TrimPrefix(string(b), prefix), true
}

// writeNativeInstructionRules updates only files carrying Persona's generated marker. A same-named user file is never
// overwritten, and stale generated chunks are removed only after their replacements have been written successfully.
func writeNativeInstructionRules(cwd string, chunks []string, antigravity bool) error {
	runtimeDir := ".claude"
	if antigravity {
		runtimeDir = ".agents"
	}
	dir := filepath.Join(cwd, runtimeDir, "rules")
	if len(chunks) == 0 {
		if _, err := os.Stat(dir); os.IsNotExist(err) {
			return nil
		}
	} else if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	wanted := map[string]bool{}
	for i := range chunks {
		wanted[assistantInstructionRuleName(i+2)] = true
	}
	stale := []string{}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasPrefix(entry.Name(), assistantInstructionRulePrefix) || !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		_, generated := nativeInstructionPart(b, antigravity)
		if wanted[entry.Name()] && !generated {
			return fmt.Errorf("assistant instruction rule %s already exists without Persona's generated marker", path)
		}
		if generated && !wanted[entry.Name()] {
			stale = append(stale, path)
		}
	}
	for i, chunk := range chunks {
		envelope := assistantInstructionRuleMarker
		if antigravity {
			envelope = antigravityInstructionHeader + envelope
		}
		if err := writeIfChanged(filepath.Join(dir, assistantInstructionRuleName(i+2)), []byte(envelope+chunk)); err != nil {
			return err
		}
	}
	for _, path := range stale {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	return nil
}

// writeAssistantInstructionFiles writes identical bounded entry files and the complete remainder in both native rule
// formats. Short instructions retain their historical one-file representation byte for byte.
func writeAssistantInstructionFiles(cwd, md string) error {
	chunks := splitAssistantInstructions(md)
	if err := writeNativeInstructionRules(cwd, chunks[1:], true); err != nil {
		return err
	}
	if err := writeNativeInstructionRules(cwd, chunks[1:], false); err != nil {
		return err
	}
	for _, name := range []string{"CLAUDE.md", "AGENTS.md"} {
		if err := writeIfChanged(filepath.Join(cwd, name), []byte(chunks[0])); err != nil {
			return err
		}
	}
	return nil
}

// assistantInstructionRemainder is the exact content after the entry chunk. Codex has no native .agents/rules loader,
// so its app-server receives this through developerInstructions; generic runtimes without verified native discovery
// receive it as context. Contiguous numbering detects a missing part instead of silently dropping instructions.
func assistantInstructionRemainder(cwd string) (string, error) {
	dir := filepath.Join(cwd, ".claude", "rules")
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return "", nil
	}
	if err != nil {
		return "", err
	}
	next := 2
	var b strings.Builder
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasPrefix(entry.Name(), assistantInstructionRulePrefix) || !strings.HasSuffix(entry.Name(), ".md") {
			continue
		}
		part, err := strconv.Atoi(strings.TrimSuffix(strings.TrimPrefix(entry.Name(), assistantInstructionRulePrefix), ".md"))
		if err != nil {
			continue // another file that happens to share the prefix is not Persona's generated sequence
		}
		raw, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return "", err
		}
		chunk, generated := nativeInstructionPart(raw, false)
		if !generated {
			if part == next {
				return "", fmt.Errorf("assistant instruction part %d lost Persona's generated marker", part)
			}
			continue
		}
		if part != next {
			return "", fmt.Errorf("assistant instruction part %d is missing before %s", next, entry.Name())
		}
		b.WriteString(chunk)
		next++
	}
	return b.String(), nil
}

// joinInstructionRemainderAndPolicy appends policy after the split remainder without deleting any source whitespace.
// Codex's existing renderer places this combined text after memory instructions, preserving the policy's final position.
func joinInstructionRemainderAndPolicy(remainder, policy string) string {
	if remainder == "" {
		return policy
	}
	if policy == "" {
		return remainder
	}
	if !strings.HasSuffix(remainder, "\n\n") {
		if strings.HasSuffix(remainder, "\n") {
			remainder += "\n"
		} else {
			remainder += "\n\n"
		}
	}
	return remainder + policy
}
