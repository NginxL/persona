    @Test fun widthsDensitiesAndCommitStatesKeepNativeGeneratedPixelsAndSemanticsEqual() {
        var width by mutableStateOf(360.dp)
        var fontScale by mutableStateOf(1f)
        var dark by mutableStateOf(false)
        var style by mutableStateOf(AppStyle.Glass)
        var version by mutableStateOf("1.42.0")
        var commit by mutableStateOf<BuildCommit?>(BuildCommit.parse(fullCommit))
        var generated by mutableStateOf(false)
        var actualFontScale by mutableStateOf(1f)
        rule.setContent {
            val base = LocalDensity.current
            CompositionLocalProvider(LocalDensity provides Density(base.density, fontScale = fontScale)) {
                actualFontScale = LocalDensity.current.fontScale
                PersonaTheme(darkTheme = dark, reduceMotion = true, style = style) {
                    Surface(modifier = Modifier.fillMaxSize(), color = PersonaTheme.palette.background) {
                        Box(Modifier.width(width)) {
                            ComparisonRows(version, commit, generated)
                        }
                    }
                }
            }
        }
        val heights = mutableMapOf<LayoutDensity, MutableMap<Int, Int>>()
        val textWidths = mutableMapOf<Pair<Int, Float>, Float>()
        val groupImages = mutableMapOf<Triple<Int, Float, Boolean>, Bitmap>()
        for (selectedWidth in listOf(360, 640)) for (density in LayoutDensity.entries)
            for (selectedScale in listOf(1f, 2f)) for (longValue in listOf(false, true)) for (present in listOf(true, false))
                for (selectedStyle in AppStyle.entries) for (selectedDark in listOf(false, true)) {
                    rule.runOnIdle {
                        generated = false
                        densityStore().setDensity(density)
                        width = selectedWidth.dp
                        fontScale = selectedScale
                        style = selectedStyle
                        dark = selectedDark
                        version = if (longValue) longVersion else "1.42.0"
                        commit = if (present) BuildCommit.parse(fullCommit) else null
                    }
                    rule.waitForIdle()
                    val label = "$selectedWidth dp ${density.key} scale=$selectedScale long=$longValue present=$present " +
                        "${selectedStyle.name} dark=$selectedDark"
                    assertEquals("$label injected scale", selectedScale, actualFontScale)
                    val native = rule.onNodeWithTag("version-row", useUnmergedTree = true)
                    native.assertIsDisplayed().assertHasNoClickAction()
                    val nativeSemantics = native.readSemantics()
                    assertEquals("$label full Version value", listOf("Version", version), nativeSemantics.text)
                    native.assertMinimumTouchTarget(label)
                    assertEquals("$label title lines", 1, native.textLines("Version"))
                    assertEquals("$label value lines", 1, native.textLines(version))
                    val nativeImage = capture("comparison-group")
                    assertTrue("$label native image is empty", nativeImage.hasVisiblePixels())
                    assertEquals("$label Commit semantics", if (present) listOf("Commit", fullCommit.take(12))
                        else listOf("Commit", "Unknown"), rule.onNodeWithTag("commit-row").readSemantics().text)
                    rule.runOnIdle { generated = true }
                    rule.waitForIdle()
                    val generatedRow = rule.onNodeWithTag("version-row", useUnmergedTree = true)
                    generatedRow.assertIsDisplayed().assertHasNoClickAction()
                    val generatedSemantics = generatedRow.readSemantics()
                    assertEquals("$label Version semantics", nativeSemantics, generatedSemantics)
                    assertEquals("$label full Version value", listOf("Version", version), generatedSemantics.text)
                    assertTrue("$label empty semantics description", generatedSemantics.descriptions.isEmpty())
                    generatedRow.assertMinimumTouchTarget(label)
                    assertEquals("$label title lines", 1, generatedRow.textLines("Version"))
                    assertEquals("$label value lines", 1, generatedRow.textLines(version))
                    rule.onNodeWithTag("commit-row").let {
                        if (present) it.assertHasClickAction() else it.assertHasNoClickAction()
                    }
                    assertEquals("$label Commit semantics", if (present) listOf("Commit", fullCommit.take(12))
                        else listOf("Commit", "Unknown"), rule.onNodeWithTag("commit-row").readSemantics().text)
                    rule.onNodeWithTag("commit-row").assertIsDisplayed()
                    val generatedImage = capture("comparison-group")
                    assertTrue("$label generated image is empty", generatedImage.hasVisiblePixels())
                    val suffix = "$selectedWidth-${density.key}-scale-$selectedScale-long-$longValue-" +
                        "${if (present) "present" else "unknown"}-${selectedStyle.name.lowercase()}-" +
                        if (selectedDark) "dark" else "light"
                    outputDirectory.resolve("native-$suffix.png").writePng(nativeImage)
                    outputDirectory.resolve("generated-$suffix.png").writePng(generatedImage)
                    assertEquals("$label dimensions", nativeImage.width to nativeImage.height,
                        generatedImage.width to generatedImage.height)
                    assertTrue("$label native/generated pixels differ", nativeImage.sameAs(generatedImage))
                    if (longValue && selectedStyle == AppStyle.Glass && !selectedDark) {
                        val key = Triple(selectedWidth, selectedScale, present)
                        groupImages[key]?.let { previous ->
                            assertFalse("$label present/unknown pixels must differ", previous.sameAs(nativeImage))
                        }
                        groupImages[key] = nativeImage
                    }
                    if (selectedWidth == 360 && density == LayoutDensity.Standard && !longValue && present &&
                        selectedStyle == AppStyle.Glass && !selectedDark) {
                        textWidths[selectedWidth to selectedScale] = generatedRow.textLayout(version).size.width.toFloat()
                    }
                    if (selectedScale == 1f && !longValue && present && selectedStyle == AppStyle.Glass && !selectedDark) {
                        val expectedGap = Tokens.Space.Standard.l.dense
                        assertEquals("$label real density-scaled token", if (density == LayoutDensity.Standard) 16.dp else 8.dp, expectedGap)
                        val probe = rule.onNodeWithTag("density-probe").fetchSemanticsNode()
                        assertEquals("$label real token pixel height", with(rule.density) { expectedGap.toPx() }, probe.boundsInRoot.height)
                        val group = rule.onNodeWithTag("comparison-group").fetchSemanticsNode().boundsInRoot
                        assertTrue("$label probe must be outside the captured three-row group", probe.boundsInRoot.bottom <= group.top)
                        heights.getOrPut(density) { mutableMapOf() }[selectedWidth] = probe.boundsInRoot.height.toInt()
                    }
                }
        for (selectedWidth in listOf(360, 640)) {
            assertTrue("Compact must reduce the shared density-scaled gap at $selectedWidth dp: $heights",
                heights.getValue(LayoutDensity.Compact).getValue(selectedWidth) <
                    heights.getValue(LayoutDensity.Standard).getValue(selectedWidth))
        }
        assertTrue("2x text must measure wider than 1x text: $textWidths",
            textWidths.getValue(360 to 2f) > textWidths.getValue(360 to 1f))
    }

    @Test fun actualVersionRowsReduceTheirVerticalPaddingWithCompactDensity() {
        // A synthetic 3x text fixture clears JRow's fixed minimum; it is a density probe, not a supported-font claim.
        // At 1x and 2x the fixed 56dp minimum can legitimately hide the 10dp-to-5dp vertical-padding change.
        var generated by mutableStateOf(false)
        var actualHeight by mutableStateOf(0)
        var actualFontScale by mutableStateOf(1f)
        val heights = mutableMapOf<Pair<Boolean, LayoutDensity>, Int>()
        rule.setContent {
            val base = LocalDensity.current
            CompositionLocalProvider(LocalDensity provides Density(base.density, fontScale = 3f)) {
                actualFontScale = LocalDensity.current.fontScale
                DensityRows(generated, onHeight = { actualHeight = it })
            }
        }
        val minimumHeight = with(rule.density) { 56.dp.roundToPx() }
        // Compose rounds each vertical-padding edge to an integer pixel; do not compare unrounded dp-to-px floats.
        val expectedReduction = 2 * with(rule.density) { 10.dp.roundToPx() - 5.dp.roundToPx() }
        for (density in LayoutDensity.entries) {
            for (generatedRow in listOf(false, true)) {
                rule.runOnIdle {
                    densityStore().setDensity(density)
                    generated = generatedRow
                }
                rule.waitForIdle()
                val row = rule.onNodeWithTag("version-row", useUnmergedTree = true)
                assertEquals("generated=$generatedRow density=${density.key} Version semantics",
                    listOf("Version", "1.42.0"), row.readSemantics().text)
                val height = rule.runOnIdle {
                    assertEquals("actual injected fontScale", 3f, actualFontScale)
                    actualHeight
                }
                assertTrue("generated=$generatedRow density=${density.key} must exceed the fixed $minimumHeight px " +
                    "minimum before attributing height to density: $heights", height > minimumHeight)
                heights[generatedRow to density] = height
            }
        }
        for (density in LayoutDensity.entries) {
            assertEquals("native/generated actual layout height at ${density.key}",
                heights.getValue(false to density), heights.getValue(true to density))
        }
        for (generatedRow in listOf(false, true)) {
            val standard = heights.getValue(generatedRow to LayoutDensity.Standard)
            val compact = heights.getValue(generatedRow to LayoutDensity.Compact)
            assertEquals("generated=$generatedRow actual Version-row vertical padding in rounded pixels: $heights",
                expectedReduction, standard - compact)
        }
    }

    @Test
    @Config(sdk = [35], qualifiers = "en-w840dp-h1200dp-420dpi")
    fun actualVersionRowsRoundNonIntegralDensityPaddingDeterministically() {
        assertEquals(420f / 160f, rule.density.density)
        actualVersionRowsReduceTheirVerticalPaddingWithCompactDensity()
    }

    @Composable
    private fun DensityRows(generated: Boolean, onHeight: (Int) -> Unit) {
        PersonaTheme(darkTheme = false, reduceMotion = true, style = AppStyle.Glass) {
            JGroupItem(GroupPosition.of(0, 3)) {
                val modifier = Modifier.testTag("version-row").onSizeChanged { onHeight(it.height) }
                if (generated) {
                    AboutVersionRow(ImmutableAboutVersionModel(AboutVersionSnapshot("1.42.0"), LocalResources.current),
                        modifier = modifier)
                } else {
                    JRow(stringResource(R.string.settings_about_version), value = "1.42.0", modifier = modifier)
                }
            }
        }
    }

    @Test fun compactLargeLongValueRetainsFullSemanticsAndEllipsizesOneVisualLine() {
        densityStore().setDensity(LayoutDensity.Compact)
        var generated by mutableStateOf(false)
        rule.setContent {
            val base = LocalDensity.current
            CompositionLocalProvider(LocalDensity provides Density(base.density, fontScale = 2f)) {
                PersonaTheme(darkTheme = false, reduceMotion = true, style = AppStyle.Brief) {
                    ComparisonRows(longVersion, BuildCommit.parse(fullCommit), generated)
                }
            }
        }
        val images = mutableListOf<Bitmap>()
        for (generatedRow in listOf(false, true)) {
            rule.runOnIdle { generated = generatedRow }
            rule.waitForIdle()
            val row = rule.onNodeWithTag("version-row", useUnmergedTree = true)
            val semantics = row.readSemantics()
            assertEquals("generated=$generatedRow full Version value", listOf("Version", longVersion), semantics.text)
            assertEquals("generated=$generatedRow title line", 1, row.textLines("Version"))
            val value = row.textLayout(longVersion)
            assertEquals("generated=$generatedRow value line", 1, value.lineCount)
            assertTrue("generated=$generatedRow long value is visually ellipsized", value.isLineEllipsized(0))
            row.assertMinimumTouchTarget("generated=$generatedRow")
            images += capture("comparison-group")
        }
        assertTrue(images.first().sameAs(images.last()))
    }

    @Test fun nativeCommitExposesItsCopyLabelAndCopiesTheFullValueWhileUnknownIsInert() {
        val notices = Notices()
        val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        clipboard.clearPrimaryClip()
        var commit by mutableStateOf<BuildCommit?>(BuildCommit.parse(fullCommit))
        rule.setContent {
            CompositionLocalProvider(LocalAppFeedback provides notices) {
                PersonaTheme(darkTheme = false, reduceMotion = true) {
                    Column {
                        Box(Modifier.testTag("native")) {
                            JGroupItem(GroupPosition.of(2, 3)) { AboutBuildCommitRow(commit, Modifier.testTag("commit-row")) }
                        }
                    }
                }
            }
        }
        val row = rule.onNodeWithTag("commit-row").assertHasClickAction().assertMinimumTouchTarget("present commit")
        assertEquals("Copy build commit", row.readSemantics().clickLabel)
        assertEquals(listOf("Commit", fullCommit.take(12)), row.readSemantics().text)
        row.performClick()
        rule.waitForIdle()
        assertEquals(fullCommit, clipboard.primaryClip?.getItemAt(0)?.text?.toString())
        assertEquals(listOf("Build commit copied"), notices.shown)
        assertEquals(64, clipboard.primaryClip?.getItemAt(0)?.text?.length)
        clipboard.clearPrimaryClip()
        notices.shown.clear()
        commit = null
        rule.waitForIdle()
        val unknown = rule.onNodeWithTag("commit-row").assertHasNoClickAction().assertMinimumTouchTarget("unknown commit")
        assertNull(unknown.readSemantics().clickLabel)
        assertEquals(listOf("Commit", "Unknown"), unknown.readSemantics().text)
        unknown.performClick()
        rule.waitForIdle()
        assertNull(clipboard.primaryClip)
        assertTrue(notices.shown.isEmpty())
    }

    @Test fun localizedVersionAndUnknownCommitKeepTheirSpokenText() {
        var language by mutableStateOf(language("en"))
        rule.setContent {
            CompositionLocalProvider(LocalContext provides language, LocalResources provides language.resources) {
                PersonaTheme(darkTheme = false, reduceMotion = true) {
                    Column {
                        Box(Modifier.testTag("version")) {
                            JGroupItem(GroupPosition.of(0, 3)) {
                                AboutVersionRow(ImmutableAboutVersionModel(AboutVersionSnapshot(longVersion), language.resources))
                            }
                        }
                        Box(Modifier.testTag("commit")) {
                            JGroupItem(GroupPosition.of(2, 3)) { AboutBuildCommitRow(null) }
                        }
                    }
                }
            }
        }
        for ((tag, expected) in mapOf(
            "en" to listOf("Version", longVersion, "Commit", "Unknown"),
            "zh" to listOf("版本", longVersion, "提交", "未知"),
            "ja" to listOf("バージョン", longVersion, "コミット", "不明"),
        )) {
            language = language(tag)
            rule.waitForIdle()
            val actual = rule.onNodeWithTag("version").readSemantics().text + rule.onNodeWithTag("commit").readSemantics().text
            assertEquals("$tag spoken row text", expected, actual)
        }
    }

    @Composable
    private fun ComparisonRows(version: String, commit: BuildCommit?, generated: Boolean = false) {
        Column(Modifier.background(PersonaTheme.palette.background).padding(Tokens.Space.m)) {
            Box(Modifier.fillMaxWidth().height(Tokens.Space.Standard.l.dense).testTag("density-probe"))
            Column(Modifier.testTag("comparison-group")) {
                JGroupItem(GroupPosition.of(0, 3)) {
                    if (generated) {
                        AboutVersionRow(ImmutableAboutVersionModel(AboutVersionSnapshot(version), LocalResources.current),
                            modifier = Modifier.testTag("version-row"))
                    } else {
                        JRow(stringResource(R.string.settings_about_version), value = version,
                            modifier = Modifier.testTag("version-row"))
                    }
                }
                JGroupItem(GroupPosition.of(1, 3)) {
                    JRow(stringResource(R.string.settings_about_build),
                        trailing = { Text("42", style = PersonaTheme.type.micro, color = PersonaTheme.palette.ink3) })
                }
                JGroupItem(GroupPosition.of(2, 3)) { AboutBuildCommitRow(commit, Modifier.testTag("commit-row")) }
            }
        }
    }

    private fun language(tag: String): Context = context.createConfigurationContext(
        Configuration(context.resources.configuration).apply { setLocale(Locale.forLanguageTag(tag)) })

    private fun densityStore() = AppStyleStore(context)

    private fun capture(tag: String): Bitmap {
        val bounds = rule.onNodeWithTag(tag, useUnmergedTree = true).fetchSemanticsNode().boundsInRoot
        val root = rule.onRoot().captureToImage().asAndroidBitmap()
        val left = bounds.left.toInt()
        val top = bounds.top.toInt()
        return Bitmap.createBitmap(root, left, top, bounds.width.toInt(), bounds.height.toInt())
    }

    private fun Bitmap.hasVisiblePixels(): Boolean {
        val background = getPixel(0, 0)
        for (y in 0 until height step 5) for (x in 0 until width step 5) {
            if (getPixel(x, y) != background) return true
        }
        return false
    }

    private fun SemanticsNodeInteraction.readSemantics(): RowSemantics {
        val node = fetchSemanticsNode()
        return RowSemantics(
            text = node.descendants().flatMap { it.config.getOrNull(SemanticsProperties.Text).orEmpty() }.map { it.text },
            descriptions = node.descendants().flatMap { it.config.getOrNull(SemanticsProperties.ContentDescription).orEmpty() },
            clickLabel = node.config.getOrNull(SemanticsActions.OnClick)?.label,
        )
    }

    private fun SemanticsNode.descendants(): List<SemanticsNode> = listOf(this) + children.flatMap { it.descendants() }

    private data class RowSemantics(val text: List<String>, val descriptions: List<String>, val clickLabel: String?)

    private fun SemanticsNodeInteraction.assertMinimumTouchTarget(label: String): SemanticsNodeInteraction {
        val bounds = fetchSemanticsNode().touchBoundsInRoot
        val minimum = with(rule.density) { Tokens.MinTouch.android.toPx() }
        assertTrue("$label touch width ${bounds.width} is below $minimum", bounds.width >= minimum)
        assertTrue("$label touch height ${bounds.height} is below $minimum", bounds.height >= minimum)
        return this
    }

    private fun SemanticsNodeInteraction.textLayout(text: String): TextLayoutResult {
        val node = fetchSemanticsNode().descendants().single {
            it.config.getOrNull(SemanticsProperties.Text).orEmpty().any { value -> value.text == text }
        }
        val layouts = mutableListOf<TextLayoutResult>()
        node.config[SemanticsActions.GetTextLayoutResult].action?.invoke(layouts)
        return layouts.single()
    }

    private fun SemanticsNodeInteraction.textLines(text: String): Int = textLayout(text).lineCount

    private class Notices : AppFeedback {
        val shown = mutableListOf<String>()
        override fun failure(error: Throwable, operation: Boolean) = false
        override fun notice(message: String): Boolean {
            shown += message
            return true
        }
    }

    private val outputDirectory by lazy {
        newAboutCaptureRun("build/about-version-matrix-shots", System.getProperty("persona.shots"))
    }

    private fun File.writePng(bitmap: Bitmap) = outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
