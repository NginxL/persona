import unittest
from unittest import mock

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location(
    "refract_about_version", Path(__file__).with_name("refract_about_version.py"))
pilot = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(pilot)
refract = pilot


def archive_with_gzip_os(os_byte):
    compressed = bytearray(gzip.compress(b"canonical tar", compresslevel=9, mtime=0))
    compressed[9] = os_byte
    packaging = types.SimpleNamespace(
        source_files=lambda commit: ["About.swift"],
        run=lambda command: "100644 blob 0000000000000000000000000000000000000000\tAbout.swift",
        run_bytes=lambda command: b"source",
        deterministic_tar=lambda prefix, entries: b"canonical tar",
        ARCHIVE_EPOCH=0,
    )
    with tempfile.TemporaryDirectory() as temporary:
        output = Path(temporary) / "source.tar.gz"
        with mock.patch.object(refract.importlib.util, "spec_from_file_location") as spec, \
                mock.patch.object(refract.importlib.util, "module_from_spec", return_value=packaging), \
                mock.patch.object(refract.gzip, "compress", return_value=bytes(compressed)):
            spec.return_value.loader = mock.Mock()
            refract.canonical_source_archive(Path("unused"), {"commit": "abc"}, output)
        return output.read_bytes()


class RefractAboutVersionTests(unittest.TestCase):
    def test_canonical_archive_normalizes_gzip_os_byte(self):
        archives = [archive_with_gzip_os(os_byte) for os_byte in (0, 3, 255)]
        self.assertEqual(archives, [archives[1]] * 3)
        self.assertEqual(archives[0][9], 3)
        self.assertEqual([gzip.decompress(archive) for archive in archives], [b"canonical tar"] * 3)


DIAGNOSTIC = (
    "UnsupportedAboutControl.swift:5:9: error [missingComponentMapping]: The component "
    "`UnsupportedAboutControlHost` has no Android mapping. "
    "Suggestion: Declare its typed target in `android.components.UnsupportedAboutControlHost`.\n"
)

VALID_KOTLIN = """// Generated by Refract; DO NOT EDIT.
// Source: AboutVersionRow.swift
import persona.core.designsystem.JRow
value = model.versionName.value
"""
REVIEWED_KOTLIN = VALID_KOTLIN.encode()


class GenerationTransactionTests(unittest.TestCase):
    def run_generate(self, generated, generate, lock=None, root=ROOT):
        argv = ["refract_about_version.py", "generate", "--cli", str(generated.parent / "refract")]
        (generated.parent / "refract").touch()
        stderr = io.StringIO()
        stdout = io.StringIO()
        with mock.patch.object(pilot, "GENERATED", generated), \
                mock.patch.object(pilot, "ROOT", root), \
                mock.patch.object(pilot, "run", generate), \
                mock.patch.object(pilot, "validate_lock", return_value=lock or {}), \
                mock.patch.object(sys, "argv", argv), contextlib.redirect_stderr(stderr), \
                contextlib.redirect_stdout(stdout):
            result = pilot.main()
        return result, stdout.getvalue(), stderr.getvalue()

    def test_valid_generate_preserves_unchanged_reviewed_bytes(self):
        with tempfile.TemporaryDirectory(prefix="persona-refract-transaction-") as temporary:
            generated = Path(temporary) / "AboutVersionRow.kt"
            generated.write_bytes(REVIEWED_KOTLIN)
            calls = []

            def deterministic_generate(cli, mode, android_out, harmony_out, sources=(pilot.SOURCE,)):
                if len(sources) == 2:
                    raise subprocess.CalledProcessError(1, str(cli), stderr=DIAGNOSTIC)
                calls.append(mode)
                generated.write_bytes(REVIEWED_KOTLIN)

            result, stdout, stderr = self.run_generate(generated, deterministic_generate,
                                                      lock={"commit": pilot.EXPECTED["commit"]},
                                                      root=generated.parent)
            self.assertEqual(result, 0, stderr)
            self.assertEqual(calls, ["generate", "generate"])
            self.assertEqual(generated.read_bytes(), REVIEWED_KOTLIN)
            self.assertIn("PASSED", stdout)

    def test_failed_restore_never_claims_the_reviewed_bytes_were_restored(self):
        with tempfile.TemporaryDirectory(prefix="persona-refract-transaction-") as temporary:
            generated = Path(temporary) / "AboutVersionRow.kt"
            generated.write_bytes(REVIEWED_KOTLIN)

            def rejected_mixed(cli, mode, android_out, harmony_out, sources=(pilot.SOURCE,)):
                raise subprocess.CalledProcessError(1, str(cli), stderr=DIAGNOSTIC)

            stderr = io.StringIO()
            result, _, stderr_text = self.run_generate(generated, rejected_mixed)
            with mock.patch.object(pilot.Path, "write_bytes", side_effect=OSError("fixture restore failure")), \
                    contextlib.redirect_stderr(stderr):
                with self.assertRaises(ValueError) as caught:
                    pilot.restore_reviewed_output(REVIEWED_KOTLIN)
            self.assertIn("Could not restore", str(caught.exception))
            self.assertNotIn("original reviewed Kotlin restored after generation failure", stderr.getvalue())

    def test_restore_failure_preserves_the_primary_error_as_secondary_context(self):
        with tempfile.TemporaryDirectory(prefix="persona-refract-transaction-") as temporary:
            generated = Path(temporary) / "AboutVersionRow.kt"
            generated.write_bytes(REVIEWED_KOTLIN)

            def primary_generation_failure(cli, mode, android_out, harmony_out, sources=(pilot.SOURCE,)):
                if len(sources) == 2:
                    raise subprocess.CalledProcessError(1, str(cli), stderr=DIAGNOSTIC)
                generated.write_bytes(b"partial unreviewed output\n")
                raise subprocess.CalledProcessError(1, str(cli), stderr="primary generator failure\n")

            with mock.patch.object(pilot, "restore_reviewed_output",
                                   side_effect=ValueError("Could not restore the reviewed Kotlin: fixture restore failure")):
                result, _, stderr = self.run_generate(generated, primary_generation_failure)
            self.assertEqual(result, 1)
            self.assertIn("primary generator failure", stderr)
            self.assertIn("Command", stderr)
            self.assertIn("Could not restore", stderr)
            self.assertIn("fixture restore failure", stderr)
            self.assertLess(stderr.index("primary generator failure"), stderr.index("Could not restore"))
            self.assertIn("secondary", stderr.lower())
            self.assertNotIn("original reviewed Kotlin restored after generation failure", stderr)
            self.assertEqual(generated.read_bytes(), b"partial unreviewed output\n")

        with tempfile.TemporaryDirectory(prefix="persona-refract-transaction-") as temporary:
            generated = Path(temporary) / "AboutVersionRow.kt"
            reviewed = REVIEWED_KOTLIN
            generated.write_bytes(reviewed)
            reviewed_digest = hashlib.sha256(reviewed).hexdigest()
            valid_calls = 0

            def two_different_generations(cli, mode, android_out, harmony_out, sources=(pilot.SOURCE,)):
                nonlocal valid_calls
                if len(sources) == 2:
                    raise subprocess.CalledProcessError(1, str(cli), stderr=DIAGNOSTIC)
                valid_calls += 1
                generated.write_bytes(reviewed + f"// unreviewed invocation {valid_calls}\n".encode())
                android_out.mkdir(parents=True, exist_ok=True)
                (android_out / "AboutVersionRow.kt").write_bytes(generated.read_bytes())

            argv = ["refract_about_version.py", "generate", "--cli", str(Path(temporary) / "refract")]
            (Path(temporary) / "refract").touch()
            stderr = io.StringIO()
            with mock.patch.object(pilot, "GENERATED", generated), \
                    mock.patch.object(pilot, "run", two_different_generations), \
                    mock.patch.object(pilot, "validate_lock", return_value={}), \
                    mock.patch.object(sys, "argv", argv), contextlib.redirect_stderr(stderr):
                self.assertEqual(pilot.main(), 1)
            self.assertEqual(valid_calls, 2)
            self.assertEqual(generated.read_bytes(), reviewed)
            self.assertEqual(hashlib.sha256(generated.read_bytes()).hexdigest(), reviewed_digest)
            self.assertNotIn(b"unreviewed invocation", generated.read_bytes())
            self.assertIn("Pinned generation is not deterministic", stderr.getvalue())
            self.assertIn("original reviewed Kotlin restored", stderr.getvalue())
            self.assertNotIn("PASSED", stderr.getvalue())


class UnsupportedInputTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="persona-refract-about-test-")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)

    def test_rejected_input_prevents_the_entrypoint_from_replacing_reviewed_kotlin(self):
        generated = self.root / "AboutVersionRow.kt"
        generated.write_bytes(b"reviewed Kotlin\n")
        calls = []

        def reject_mixed_input(cli, mode, android_out, harmony_out, sources=(pilot.SOURCE,)):
            calls.append((mode, sources))
            if len(sources) == 2:
                raise subprocess.CalledProcessError(1, str(cli), stderr=DIAGNOSTIC)
            # A silent accepted negative followed by a valid generate must not publish the valid row.
            if mode == "generate" and [call[0] for call in calls].count("generate") == 1:
                generated.write_bytes(b"unreviewed replacement\n")
                return
            raise subprocess.CalledProcessError(1, str(cli), stderr=DIAGNOSTIC)

        argv = ["refract_about_version.py", "generate", "--cli", str(self.root / "refract")]
        (self.root / "refract").touch()
        stderr = io.StringIO()
        with mock.patch.object(pilot, "GENERATED", generated), \
                mock.patch.object(pilot, "run", reject_mixed_input), \
                mock.patch.object(pilot, "validate_lock", return_value={}), \
                mock.patch.object(sys, "argv", argv), contextlib.redirect_stderr(stderr):
            self.assertEqual(pilot.main(), 1)
        self.assertEqual(generated.read_bytes(), b"reviewed Kotlin\n")
        self.assertEqual([mode for mode, _ in calls], ["check", "generate", "generate"])
        self.assertEqual([source.name for _, sources in calls for source in sources],
                         ["AboutVersionRow.swift", "UnsupportedAboutControl.swift"] * 2 +
                         ["AboutVersionRow.swift"])
        self.assertIn("UnsupportedAboutControl.swift:5:9", stderr.getvalue())
        self.assertIn("UnsupportedAboutControlHost", stderr.getvalue())
        self.assertIn("Suggestion: Declare its typed target", stderr.getvalue())

    def test_silent_acceptance_missing_diagnostics_and_partial_output_all_fail(self):
        for behavior in ("silent success", "missing diagnostics", "partial output"):
            with self.subTest(behavior=behavior), mock.patch.object(pilot, "GENERATED", self.root / "generated.kt"):
                (self.root / "generated.kt").write_bytes(b"reviewed\n")

                def broken_generator(cli, mode, android_out, harmony_out, sources=(pilot.SOURCE,)):
                    if behavior == "partial output":
                        android_out.mkdir(parents=True)
                        (android_out / "AboutVersionRow.kt").write_text("partial sibling")
                    if behavior != "silent success":
                        detail = DIAGNOSTIC if behavior == "partial output" else "refract: failed\n"
                        raise subprocess.CalledProcessError(1, str(cli), stderr=detail)

                with mock.patch.object(pilot, "run", broken_generator):
                    with self.assertRaises(ValueError) as caught:
                        pilot.check_unsupported_input(self.root / "refract", self.root / behavior)
                self.assertIsInstance(caught.exception, ValueError)


if __name__ == "__main__":
    unittest.main()
